#conveyer belt background
def make_conveyor_background():
    """
    Draws a realistic rubber conveyor belt texture with:
    - Dark grey belt base
    - Horizontal ridges
    - Subtle lighting gradient
    - Random noise for texture
    """
    bg = np.zeros((IMG_H, IMG_W, 3), dtype=np.uint8)

    # Base belt color (dark charcoal rubber)
    belt_color = np.array([45, 45, 42], dtype=np.uint8)
    bg[:] = belt_color

    # Horizontal ribs (every ~22px, slightly lighter)
    rib_spacing = random.randint(18, 26)
    rib_color   = np.array([60, 60, 57], dtype=np.uint8)
    for y in range(0, IMG_H, rib_spacing):
        thickness = random.randint(2, 4)
        bg[y:y+thickness, :] = rib_color

    # Overhead lighting: bright center, darker edges
    for y in range(IMG_H):
        for x in range(IMG_W):
            dist = math.hypot(x - IMG_W/2, y - IMG_H/2) / math.hypot(IMG_W/2, IMG_H/2)
            factor = 1.0 - 0.35 * dist
            bg[y, x] = np.clip(bg[y, x] * factor, 0, 255).astype(np.uint8)

    # Random noise texture
    noise = np.random.randint(-10, 10, bg.shape, dtype=np.int16)
    bg    = np.clip(bg.astype(np.int16) + noise, 0, 255).astype(np.uint8)

    #  motion blur (horizontal, simulates belt movement)
    if random.random() < 0.4:
        ksize = random.choice([3, 5])
        kernel = np.zeros((ksize, ksize))
        kernel[ksize//2, :] = 1.0 / ksize
        bg = cv2.filter2D(bg, -1, kernel)

    return bg

#part shapes
def draw_washer(canvas, cx, cy, radius, color, defect=None):
    """
    Draws a flat metal washer.
    Defects: scratch, wrong_color, wrong_orientation(ellipse = tilted)
    """
    inner_r = max(int(radius * 0.35), 4)

    if defect == "wrong_orientation":
        # Draw as ellipse to simulate a tilted washer viewed at angle
        axes_outer = (radius, int(radius * 0.5))
        axes_inner = (inner_r, int(inner_r * 0.5))
        cv2.ellipse(canvas, (cx, cy), axes_outer, 0, 0, 360, color, -1)
        cv2.ellipse(canvas, (cx, cy), axes_outer, 0, 0, 360, _darken(color, 0.6), 2)
        cv2.ellipse(canvas, (cx, cy), axes_inner, 0, 0, 360, _conveyor_hole_color(), -1)
    else:
        draw_color = _wrong_color(color) if defect == "wrong_color" else color
        cv2.circle(canvas, (cx, cy), radius,      draw_color,             -1)
        cv2.circle(canvas, (cx, cy), radius,      _darken(color, 0.6),     2)
        if defect == "missing_feature":
            # Missing inner hole = manufacturing defect
            pass
        else:
            cv2.circle(canvas, (cx, cy), inner_r, _conveyor_hole_color(), -1)

    _add_metallic_sheen(canvas, cx, cy, radius)

    if defect == "scratch":
        _draw_scratches(canvas, cx, cy, radius)

    return cx, cy, radius * 2, radius * 2

def draw_bolt(canvas, cx, cy, size, color, defect=None):
    """
    Draws a hex-head bolt (hexagon head + rectangular shank).
    """
    angle_offset = 0
    if defect == "wrong_orientation":
        angle_offset = random.randint(25, 70)

    draw_color = _wrong_color(color) if defect == "wrong_color" else color

    # Hex head
    pts = []
    for i in range(6):
        a = math.radians(60 * i + angle_offset)
        px = int(cx + size * math.cos(a))
        py = int(cy + size * math.sin(a))
        pts.append([px, py])
    pts = np.array(pts, np.int32).reshape((-1, 1, 2))
    cv2.fillPoly(canvas, [pts], draw_color)
    cv2.polylines(canvas, [pts], True, _darken(color, 0.5), 2)

    # Shank
    shank_w = int(size * 0.45)
    shank_h = int(size * 1.4)
    shank_x = cx - shank_w // 2
    shank_y = cy + int(size * 0.8)
    if defect != "missing_feature":
        cv2.rectangle(canvas, (shank_x, shank_y),
                      (shank_x + shank_w, shank_y + shank_h), draw_color, -1)
        cv2.rectangle(canvas, (shank_x, shank_y),
                      (shank_x + shank_w, shank_y + shank_h), _darken(color, 0.5), 1)

    _add_metallic_sheen(canvas, cx, cy, size)

    if defect == "scratch":
        _draw_scratches(canvas, cx, cy, size)

    bbox_h = size * 2 + shank_h if defect != "missing_feature" else size * 2
    return cx, cy, size * 2, bbox_h

def draw_cap(canvas, cx, cy, radius, color, defect=None):
    """
    Draws a plastic cap (circle with raised center nub).
    """
    draw_color = _wrong_color(color) if defect == "wrong_color" else color

    if defect == "wrong_orientation":
        # Viewed from side — flat rectangle
        w, h = radius * 2, int(radius * 0.6)
        cv2.rectangle(canvas, (cx - radius, cy - h//2),
                      (cx + radius, cy + h//2), draw_color, -1)
        cv2.rectangle(canvas, (cx - radius, cy - h//2),
                      (cx + radius, cy + h//2), _darken(color, 0.5), 2)
    else:
        cv2.circle(canvas, (cx, cy), radius,draw_color,-1)
        cv2.circle(canvas, (cx, cy), radius, _darken(color, 0.5), 2)
        if defect != "missing_feature":
            nub_r = max(int(radius * 0.28), 3)
            nub_color = _darken(draw_color, 0.75)
            cv2.circle(canvas, (cx, cy), nub_r, nub_color, -1)

    if defect == "scratch":
        _draw_scratches(canvas, cx, cy, radius)

    return cx, cy, radius * 2, radius * 2

def _darken(color, factor):
    return tuple(int(c * factor) for c in color)

def _wrong_color(color):
    """Shift hue drastically for wrong_color defect."""
    r, g, b = color
    return (b, r, g)   # channel swap

def _conveyor_hole_color():
    v = random.randint(30, 50)
    return (v, v, v)

def _add_metallic_sheen(canvas, cx, cy, r):
    """Adds a small highlight ellipse to simulate metallic reflection."""
    hx = cx - int(r * 0.25)
    hy = cy - int(r * 0.25)
    hl_a = max(int(r * 0.3), 2)
    hl_b = max(int(r * 0.15), 1)
    overlay = canvas.copy()
    cv2.ellipse(overlay, (hx, hy), (hl_a, hl_b), -30, 0, 360, (220, 220, 220), -1)
    cv2.addWeighted(overlay, 0.25, canvas, 0.75, 0, canvas)

def _draw_scratches(canvas, cx, cy, r):
    """Draws 1–3 random scratch lines across the part surface."""
    n = random.randint(1, 3)
    for _ in range(n):
        angle  = random.uniform(0, math.pi)
        length = random.uniform(r * 0.5, r * 1.2)
        x1 = int(cx + length * math.cos(angle))
        y1 = int(cy + length * math.sin(angle))
        x2 = int(cx - length * math.cos(angle))
        y2 = int(cy - length * math.sin(angle))
        scratch_color = (random.randint(180,220),)*3
        thickness = random.choice([1, 1, 2])
        cv2.line(canvas, (x1, y1), (x2, y2), scratch_color, thickness)

def _part_color():
    """Generates a realistic metal or plastic part color."""
    palettes = [
        (random.randint(160,200), random.randint(160,200), random.randint(160,200)),  # silver
        (random.randint(100,140), random.randint(85,115),  random.randint(60,90)),    # brass
        (random.randint(60,90),   random.randint(60,90),   random.randint(60,90)),    # dark steel
        (random.randint(30,70),   random.randint(100,160), random.randint(180,230)),  # blue cap
        (random.randint(200,240), random.randint(60,100),  random.randint(30,70)),    # red cap
        (random.randint(30,70),   random.randint(160,210), random.randint(60,100)),   # green cap
    ]
    return random.choice(palettes)

def bbox_to_yolo(cx, cy, bw, bh, img_w, img_h):
    """Converts pixel bbox to YOLO normalized format."""
    x_c = cx / img_w
    y_c = cy / img_h
    w   = bw / img_w
    h   = bh / img_h
    return x_c, y_c, w, h

def clamp(v, lo, hi):
    return max(lo, min(hi, v))

#image generator
DRAW_FNS = [draw_washer, draw_bolt, draw_cap]

# Defect probability per part: 60% good, 10% each defect
DEFECT_WEIGHTS = [0.60, 0.10, 0.10, 0.10, 0.10]
DEFECT_KEYS    = [None, "scratch", "missing_feature", "wrong_color", "wrong_orientation"]

def generate_image(idx):
    canvas = make_conveyor_background()
    labels = []
    n_parts = random.randint(*PARTS_PER_IMG)
    placed  = []

    for _ in range(n_parts):
        # Pick random size and position
        size = random.randint(28, 70)
        margin = size + 5
        for attempt in range(40):
            cx = random.randint(margin, IMG_W - margin)
            cy = random.randint(margin, IMG_H - margin)
            # Check overlap with already-placed parts
            ok = all(math.hypot(cx-px, cy-py) > (size + ps + 8)
                     for px, py, ps in placed)
            if ok:
                break
        else:
            continue  # skip if no room

        color  = _part_color()
        draw_fn = random.choice(DRAW_FNS)
        defect  = random.choices(DEFECT_KEYS, weights=DEFECT_WEIGHTS)[0]
        cls_id  = 0 if defect is None else list(DEFECT_KEYS).index(defect)

        cx_out, cy_out, bw, bh = draw_fn(canvas, cx, cy, size, color, defect)
        placed.append((cx, cy, size))

        # Build YOLO label
        bw = min(bw, IMG_W * 0.95)
        bh = min(bh, IMG_H * 0.95)
        xc, yc, nw, nh = bbox_to_yolo(cx_out, cy_out, bw, bh, IMG_W, IMG_H)
        xc = clamp(xc, 0.001, 0.999)
        yc = clamp(yc, 0.001, 0.999)
        nw = clamp(nw, 0.001, 0.999)
        nh = clamp(nh, 0.001, 0.999)
        labels.append(f"{cls_id} {xc:.6f} {yc:.6f} {nw:.6f} {nh:.6f}")

    return canvas, labels

#augmentation
def augment_image(img):
    """
    Applies random augmentations:
    - Brightness / contrast jitter
    - Gaussian blur
    - Salt-and-pepper noise
    - Horizontal / vertical flip
    """
    # Brightness & contrast
    alpha = random.uniform(0.7, 1.3)
    beta  = random.randint(-20, 20)
    img   = cv2.convertScaleAbs(img, alpha=alpha, beta=beta)

    # Gaussian blur
    if random.random() < 0.3:
        ksize = random.choice([3, 5])
        img   = cv2.GaussianBlur(img, (ksize, ksize), 0)

    # Salt and pepper noise
    if random.random() < 0.2:
        n_noise = random.randint(100, 500)
        for _ in range(n_noise):
            nx = random.randint(0, IMG_W-1)
            ny = random.randint(0, IMG_H-1)
            img[ny, nx] = (255, 255, 255) if random.random() > 0.5 else (0, 0, 0)

    return img

def save_dataset():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    splits = {
        "train": int(TOTAL_IMAGES * 0.80),
        "val":   int(TOTAL_IMAGES * 0.10),
        "test":  int(TOTAL_IMAGES * 0.10),
    }

    stats = {cls: 0 for cls in CLASSES.values()}
    img_idx = 0

    for split, count in splits.items():
        img_dir = OUTPUT_DIR / "images" / split
        lbl_dir = OUTPUT_DIR / "labels" / split
        img_dir.mkdir(parents=True, exist_ok=True)
        lbl_dir.mkdir(parents=True, exist_ok=True)

        print(f"\n Generating {count} images for [{split}] split...")
        for i in tqdm(range(count), ncols=80):
            img, labels = generate_image(img_idx)
            img = augment_image(img)

            fname = f"part_{img_idx:05d}"
            cv2.imwrite(str(img_dir / f"{fname}.jpg"), img,
                        [cv2.IMWRITE_JPEG_QUALITY, 92])
            with open(lbl_dir / f"{fname}.txt", "w") as f:
                f.write("\n".join(labels))

            for lbl in labels:
                cls_id = int(lbl.split()[0])
                stats[CLASSES[cls_id]] += 1

            img_idx += 1


    yaml_path = OUTPUT_DIR / "data.yaml"
    yaml_content = f"""# YOLOv8 dataset config — auto-generated by generate_data.py
path: {OUTPUT_DIR.resolve()}
train: images/train
val:   images/val
test:  images/test

nc: {len(CLASSES)}
names: {list(CLASSES.values())}
"""
    yaml_path.write_text(yaml_content)

    print("\n" + "="*55)
    print(" Dataset generation complete!")
    print(f"Total images : {TOTAL_IMAGES}")
    print(f"Output dir   : {OUTPUT_DIR.resolve()}")
    print(f"\n  Label distribution:")
    for cls, cnt in stats.items():
        print(f"     {cls:<20} : {cnt}")
    print(f"\n data.yaml written → {yaml_path.resolve()}")
    print("="*55)


if __name__ == "__main__":
    save_dataset()