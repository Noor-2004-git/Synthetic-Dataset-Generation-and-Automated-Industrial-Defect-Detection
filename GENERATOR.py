#configuration section
TOTAL_IMAGES   = 1200   # total images (auto-split 80/10/10)
IMG_W, IMG_H   = 640, 640
PARTS_PER_IMG  = (1, 4)  # min/max parts per image
OUTPUT_DIR     = Path("../dataset")
SEED           = 42

CLASSES = {
    0: "good",
    1: "scratch",
    2: "missing_feature",
    3: "wrong_color",
    4: "wrong_orientation",
}

random.seed(SEED)
