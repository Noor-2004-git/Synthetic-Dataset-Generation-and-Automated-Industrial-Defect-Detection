import cv2
import numpy as np
import os
import random
import shutil
from pathlib import Path
from tqdm import tqdm
import albumentations as A

DATASET_DIR= Path("../dataset")
AUGMENT_FACTOR = 2 # generate N extra copies per original image
SEED = 42
random.seed(SEED)
np.random.seed(SEED)

#  AUGMENTATION PIPELINE
# Each transform is carefully chosen to simulate real camera conditions:
# ColorJitter / CLAHE:different lighting conditions
# GaussNoise / Blur:camera quality variation
# Perspective:camera angle not perfectly overhead
# HueSaturation:slight color temperature shifts
# RandomShadow :shadow from nearby objects
# Geometric transforms that flip/rotate the image also transform the bboxes.

def build_pipeline():
    return A.Compose(
        [
            # Spatial transforms (bboxes auto-adjusted)
            A.HorizontalFlip(p=0.5),
            A.VerticalFlip(p=0.3),
            A.RandomRotate90(p=0.4),
            A.Rotate(limit=15, border_mode=cv2.BORDER_REFLECT_101, p=0.5),
            A.Perspective(scale=(0.03, 0.08), p=0.4),
            A.ShiftScaleRotate(
                shift_limit=0.05, scale_limit=0.15,
                rotate_limit=10,  border_mode=cv2.BORDER_REFLECT_101, p=0.5
            ),

            #Pixel-level transforms
            A.OneOf([
                A.GaussNoise(var_limit=(10, 80), p=1.0),
                A.ISONoise(color_shift=(0.01, 0.05), intensity=(0.1, 0.5), p=1.0),
            ], p=0.5),

            A.OneOf([
                A.MotionBlur(blur_limit=5, p=1.0),
                A.GaussianBlur(blur_limit=(3, 5), p=1.0),
                A.MedianBlur(blur_limit=3, p=1.0),
            ], p=0.35),

            A.CLAHE(clip_limit=4.0, tile_grid_size=(8, 8), p=0.4),
            A.RandomBrightnessContrast(
                brightness_limit=0.3, contrast_limit=0.3, p=0.6
            ),
            A.HueSaturationValue(
                hue_shift_limit=8, sat_shift_limit=30, val_shift_limit=25, p=0.5
            ),
            A.RandomGamma(gamma_limit=(70, 130), p=0.3),
            A.RandomShadow(
                shadow_roi=(0, 0, 1, 1), num_shadows_lower=1,
                num_shadows_upper=2, shadow_dimension=5, p=0.3
            ),

            # Compression artifacts
            A.ImageCompression(quality_lower=70, quality_upper=100, p=0.3),
        ],
        bbox_params=A.BboxParams(
            format="yolo",
            label_fields=["class_labels"],
            min_area=200,           # drop boxes that become tiny after transform
            min_visibility=0.4,     # drop boxes occluded >60%
        ),
    )

#READ / WRITE HELPERS
def read_yolo_labels(label_path):
    """Returns list of (class_id, xc, yc, w, h)."""
    labels = []
    if label_path.exists():
        for line in label_path.read_text().strip().splitlines():
            parts = line.split()
            if len(parts) == 5:
                cls = int(float(parts[0]))
                box = list(map(float, parts[1:]))
                labels.append((cls, *box))
    return labels

def write_yolo_labels(label_path, class_labels, bboxes):
    lines = []
    for cls, (xc, yc, w, h) in zip(class_labels, bboxes):
        lines.append(f"{cls} {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}")
    label_path.write_text("\n".join(lines))

#PER-SPLIT AUGMENTATION
def augment_split(split="train"):
    img_dir = DATASET_DIR / "images" / split
    lbl_dir = DATASET_DIR / "labels" / split

    images = sorted(img_dir.glob("*.jpg"))
    if not images:
        print(f"No images found in {img_dir}, skipping.")
        return

    pipeline    = build_pipeline()
    new_count   = 0
    start_idx   = max(int(p.stem.split("_")[-1]) for p in images) + 1
    running_idx = start_idx

    print(f"\n Augmenting [{split}] — {len(images)} originals × {AUGMENT_FACTOR} copies...")
    for img_path in tqdm(images, ncols=80):
        img    = cv2.imread(str(img_path))
        img    = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        raw_labels   = read_yolo_labels(lbl_dir / (img_path.stem + ".txt"))
        class_ids    = [l[0] for l in raw_labels]
        bboxes       = [l[1:] for l in raw_labels]  # (xc, yc, w, h)

        for aug_i in range(AUGMENT_FACTOR):
            try:
                result = pipeline(
                    image=img,
                    bboxes=bboxes,
                    class_labels=class_ids
                )
            except Exception:
                continue

            aug_img        = cv2.cvtColor(result["image"], cv2.COLOR_RGB2BGR)
            aug_bboxes     = result["bboxes"]
            aug_cls        = result["class_labels"]

            if not aug_cls:
                continue # skip if all boxes were transformed away

            fname = f"aug_{running_idx:06d}"
            cv2.imwrite(
                str(img_dir / f"{fname}.jpg"), aug_img,
                [cv2.IMWRITE_JPEG_QUALITY, 90]
            )
            write_yolo_labels(
                lbl_dir / f"{fname}.txt",
                aug_cls, aug_bboxes
            )
            running_idx += 1
            new_count   += 1

    print(f"{new_count} augmented images added to [{split}]")
    print(f"Total in [{split}]: {len(list(img_dir.glob('*.jpg')))}")

