def print_stats():
    CLASSES = ["good","scratch","missing_feature","wrong_color","wrong_orientation"]
    print("\n" + "="*55)
    print("FINAL DATASET STATISTICS")
    print("="*55)
    for split in ["train", "val", "test"]:
        lbl_dir = DATASET_DIR / "labels" / split
        img_dir = DATASET_DIR / "images" / split
        n_imgs  = len(list(img_dir.glob("*.jpg")))
        counts  = {c: 0 for c in CLASSES}
        for lbl_file in lbl_dir.glob("*.txt"):
            for line in lbl_file.read_text().strip().splitlines():
                if line:
                    cls = int(float(line.split()[0]))
                    if cls < len(CLASSES):
                        counts[CLASSES[cls]] += 1
        total_boxes = sum(counts.values())
        print(f"\n  [{split}]  {n_imgs} images | {total_boxes} labels")
        for cls, cnt in counts.items():
            bar = "█" * (cnt // 20)
            print(f"    {cls:<20} {cnt:>5}  {bar}")
    print("="*55)


if __name__ == "__main__":
    # Only augment train split — val/test stay clean for honest evaluation
    augment_split("train")
